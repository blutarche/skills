class SampleTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.tmp = tempfile.TemporaryDirectory()
        repo = Repo(Path(cls.tmp.name) / "repo")
        base_text = "".join(f"row {n}\n" for n in range(1, 41))
        base: dict[str, str] = {f"gen30/f{i:02}.txt": base_text for i in range(30)}
        base["big/one.txt"] = "".join(f"line {n}\n" for n in range(1, 101))
        repo.put(base)
        cls.base = repo.commit("base")
        head: dict[str, str] = {}
        for i in range(30):
            changed = {5, 15, 25} | (set(range(30, 36)) if i == 17 else set())
            head[f"gen30/f{i:02}.txt"] = "".join(f"ROW {n}\n" if n in changed else f"row {n}\n" for n in range(1, 41))
        head.update({f"gen50/f{i:02}.txt": f"value {i}\n" for i in range(50)})
        head.update({f"gen200/f{i:03}.txt": f"v{i}\n" for i in range(200)})
        head["big/one.txt"] = "".join(f"LINE {n}\n" if 11 <= n <= 70 else f"line {n}\n" for n in range(1, 101))
        repo.put(head)
        cls.head = repo.commit("head")
        cls.root = repo.path
        cls.files = build_tour.load_changed_files(repo.path, cls.base, cls.head)
        cls.spec = make_spec(
            [
                word_group("g30", ["gen30/*"]),
                word_group("g50", ["gen50/*"], "bulk"),
                word_group("g200", ["gen200/*"], "lockfile"),
                word_group("big", ["big/*"]),
            ]
        )

    @classmethod
    def tearDownClass(cls) -> None:
        cls.tmp.cleanup()

    def run_seed(self, seed: int) -> digest.Digest:
        return digest.classify(self.spec, self.files, self.root, self.base, self.head, seed)

    def test_same_seed_same_result(self) -> None:
        self.assertEqual(self.run_seed(7), self.run_seed(7))

    def test_different_seeds_pick_differently(self) -> None:
        picks = {tuple((s.path, s.start) for s in group_of(self.run_seed(seed), "g30").samples) for seed in range(10)}
        self.assertGreater(len(picks), 1)

    def test_largest_file_first(self) -> None:
        for seed in range(10):
            samples = group_of(self.run_seed(seed), "g30").samples
            self.assertEqual(samples[0].path, "gen30/f17.txt")
            self.assertEqual(len({s.path for s in samples}), len(samples))

    def test_sample_counts(self) -> None:
        d = self.run_seed(1)
        self.assertEqual([len(group_of(d, gid).samples) for gid in ("g30", "g50", "g200", "big")], [3, 5, 8, 1])

    def test_sample_runs_are_widened_and_cut(self) -> None:
        d = self.run_seed(1)
        self.assertEqual(group_of(d, "big").samples, [digest.Sample("big/one.txt", "new", 9, 48)])
        valid = {(3, 7), (13, 17), (23, 27), (28, 37)}
        for s in group_of(d, "g30").samples:
            self.assertEqual(s.side, "new")
            self.assertIn((s.start, s.end), valid)

    def test_sampled_lines(self) -> None:
        d = self.run_seed(1)
        expected = 0
        for g in d.groups:
            for s in g.samples:
                fd = self.files[s.path]
                changed = fd.added if s.side == "new" else fd.removed
                expected += sum(1 for n in range(s.start, s.end + 1) if n in changed)
        self.assertEqual(d.lines["sampled"], expected)
        self.assertEqual(sum(1 for n in range(9, 49) if n in self.files["big/one.txt"].added), 38)

    def test_files_are_not_mutated(self) -> None:
        before = {p: (set(fd.added), set(fd.removed)) for p, fd in self.files.items()}
        self.run_seed(2)
        self.assertEqual({p: (set(fd.added), set(fd.removed)) for p, fd in self.files.items()}, before)


